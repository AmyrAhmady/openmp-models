export function isValidVehicleComponent(vehicleModel: number, componentId: number): boolean {
    if (vehicleModel === 576 && (componentId === 1192 || componentId === 1193)) {
        return true;
    }

    const vehicleIndex = vehicleModel - FIRST_VEHICLE_MODEL_ID;
    const componentIndex = componentId - COMPONENT_ID_OFFSET;
    if (
        vehicleIndex < 0 ||
        vehicleIndex >= vehicleComponentMasks.length / WORDS_PER_VEHICLE ||
        componentIndex < 0 ||
        componentIndex >= COMPONENTS_PER_VEHICLE
    ) {
        return false;
    }

    const word =
        vehicleComponentMasks[vehicleIndex * WORDS_PER_VEHICLE + (componentIndex >>> 5)] ?? 0;
    return (word & (1 << (componentIndex & 31))) !== 0;
}

export function getValidVehicleModifications(
    vehicleModel: number,
    modifications: readonly VehicleModification[]
): VehicleModification[] {
    return modifications.filter((modification) =>
        isValidVehicleComponent(vehicleModel, Number(modification.id))
    );
}
